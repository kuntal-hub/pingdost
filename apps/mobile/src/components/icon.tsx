interface IconProps {
  icon: LucideIcon;
  size?: number;
  /** A palette color, or any color string. */
  color?: ColorName | (string & {});
  filled?: boolean;
  strokeWidth?: number;
}

/** A decorative icon: the control around it carries the accessibility label. */
export function Icon({
  icon: Glyph,
  size = 22,
  color = 'foreground',
  filled = false,
  strokeWidth = 2.2,
}: IconProps) {
  const palette = usePalette();
  const stroke = palette[color as ColorName] ?? color;
  return (
    <Glyph
      size={size}
      color={stroke}
      fill={filled ? stroke : 'none'}
      strokeWidth={strokeWidth}
      accessibilityElementsHidden
      importantForAccessibility="no"
    />
  );
}
